a=10

a+=5  // a = a+5
document.writeln(`a value using a+=5 = ${a}`)

a-=5  // a = a-5
document.writeln(`<br>a value using a-=5 = ${a}`)

a*=5  // a = a*5
document.writeln(`<br>a value using a*=5 = ${a}`)

a/=5  // a = a/5
document.writeln(`<br>a value using a/=5 = ${a}`)

a%=5  // a = a%5
document.writeln(`<br>a value using a%=5 = ${a}`)


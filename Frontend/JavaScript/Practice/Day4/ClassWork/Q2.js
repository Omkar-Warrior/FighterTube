// Q2) Pre & Post Decrement + Logical
// Write a program:
// Initialize x = 5, y = 3
// Apply:
// Pre-decrement (--x)
// Post-decrement (y--)
// Use logical operator (&&) to compare conditions
// Print result
// 👉 Expected Concept:
//  Decrement + Logical AND


let x=5,y=3

document.writeln(`Original Value of x is ${x} Pre Decrement :- Value of --x = ${--x}`)

document.writeln(`<br>Original Value of y is ${y} Post Decrement :- Value of y-- = ${y--}`)

document.writeln(`<br>Used Logical And (&&) Operator ${x<5 && y<=4}`)

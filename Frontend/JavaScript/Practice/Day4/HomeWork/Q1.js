// Q1) Mixed Increment-Decrement
// Write a program:
// a = 5, b = 10
// Apply:
// ++a + b--
// Print final values of a and b

let a=5,b=10
document.writeln(`<br>Original Value of a is ${a} and Original Value of b is ${b} `)
res = ++a + b--
document.writeln(`<br>Value of a is ${a} and value of b is ${b} and Result = ${res} `)
